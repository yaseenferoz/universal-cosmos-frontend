const mergedImagery: Partial<Record<ObjectId, ObjectImagery>> = { ...imageryById };
for (const [body, surface] of Object.entries(bodyMaps as unknown as Record<ObjectId, TextureAsset>)) {
  mergedImagery[body] = { ...mergedImagery[body], surface, missing: BODY_MAP_NOTES[body] ?? [] };
}
// Bodies drawn with a NASA shape model: a JPL map, where present, is only a fallback.
for (const body of shapeModelIds()) {
  const existing = mergedImagery[body];
  if (!existing) continue;
  mergedImagery[body] = {
    ...existing,
    missing: existing.surface
      ? ["The published NASA/JPL shape model (baked texture) is shown; this JPL cartographic map is used only if the model cannot load."]
      : MODEL_ONLY.missing,
  };
}

/** Imagery for any catalog object; generated bodies without a map get an explicit notice. */
export function imageryFor(id: ObjectId): ObjectImagery {
  return mergedImagery[id] ?? (shapeModelFor(id) ? MODEL_ONLY : NO_IMAGERY);
}

/** Hand-curated bodies (with an imagery entry, even an empty one) get the full renderer. */
export function hasCuratedImagery(id: ObjectId): boolean {
  return Object.prototype.hasOwnProperty.call(mergedImagery, id);
}
