import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { PerspectiveCamera, Vector3 } from "three";
import { CameraController } from "./CameraController";

// Keep navigation tests CPU-only. OrbitControls' browser gesture implementation
// is upstream; exercise our free-flight pivot and input lifecycle around it.
vi.mock("three/addons/controls/OrbitControls.js", () => ({
  OrbitControls: class extends EventTarget {
    target = new Vector3();
    constructor(private readonly camera: PerspectiveCamera) {
      super();
    }
    update(): void {
      this.camera.lookAt(this.target);
    }
    dispose(): void {}
  },
}));

describe("free-flight controller", () => {
  beforeEach(() => {
    vi.stubGlobal("window", new EventTarget());
    vi.stubGlobal("document", new EventTarget());
  });
  afterEach(() => vi.unstubAllGlobals());

  function setup() {
    const camera = new PerspectiveCamera();
    camera.position.set(0, 0, 10);
    camera.lookAt(0, 0, 0);
    const element = new EventTarget() as unknown as HTMLElement;
    const controller = new CameraController(camera, element, () => undefined);
    controller.setMode("free");
    return { camera, element, controller };
  }

  it("keeps travelling after dolly reaches the previous orbit pivot", () => {
    const { camera, controller } = setup();
    expect(controller.controls.target.z).toBeCloseTo(6);
    // Emulate the camera movement generated by wheel or two-touch dolly.
    camera.position.z = 6.1;
    controller.update(0);
    expect(controller.controls.target.z).toBeCloseTo(2.1);
    camera.position.z = 2.2;
    controller.update(0);
    expect(controller.controls.target.z).toBeCloseTo(-1.8);
    expect(camera.position.distanceTo(controller.controls.target)).toBeCloseTo(
      4,
    );
    controller.dispose();
  });

  it("releases movement when the canvas loses focus to a dialog", () => {
    const { camera, element, controller } = setup();
    const key = Object.assign(new Event("keydown", { cancelable: true }), {
      code: "KeyW",
    });
    element.dispatchEvent(key);
    controller.update(0.1);
    expect(camera.position.z).toBeLessThan(10);
    element.dispatchEvent(new Event("blur"));
    const stopped = camera.position.clone();
    controller.update(0.1);
    expect(camera.position).toEqual(stopped);
    controller.dispose();
  });
});
